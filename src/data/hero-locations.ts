/** All locations for a country code, in display order. */
export const HERO_LOCATIONS_BY_COUNTRY: Record<string, HeroLocation[]> =
  HERO_LOCATIONS.reduce((acc, l) => {
    (acc[l.code] ||= []).push(l);
    return acc;
  }, {} as Record<string, HeroLocation[]>);

/** True if (code, slug) is a known location — used to validate hero uploads. */
export function isKnownLocation(code: string, slug: string): boolean {
  const list = HERO_LOCATIONS_BY_COUNTRY[String(code).toUpperCase()];
  return !!list && list.some((l) => l.slug === slug);
}
